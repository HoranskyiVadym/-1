import random

ADJ = ["місячний", "сонячний", "лісовий", "болотний", "гірський", "морський", "вогняний", "крижаний",
       "темний", "світлий", "дикий", "древній", "отруйний", "солодкий", "гіркий", "срібний",
       "золотий", "нічний", "ранковий", "магічний"]
CATS = ["Корінь", "Гриб", "Лист", "Ягода", "Кристал", "Мох", "Насіння", "Кора", "Пелюстка", "Попіл"]
EFFECTS = ["Лікування", "Сили", "Швидкості", "Захисту", "Невидимості",
           "Розуму", "Удачі", "Вогню", "Холоду", "Нічного зору"]
TIERS = ["слабке", "мале", "звичайне", "велике", "могутнє"]

# 20 x 10 = 200 інгредієнтів
INGREDIENTS = {f"{c} [{a}]": c for a in ADJ for c in CATS}

# 10 x 5 = 50 зілля: рецепт = 2 категорії інгредієнтів
_r = random.Random(42)
POTIONS = [{"name": f"Зілля {e} ({t})",
            "recipe": _r.sample(CATS, 2),
            "price": _r.randint(20, 60)}
           for e in EFFECTS for t in TIERS]
PRICES = {p["name"]: p["price"] for p in POTIONS}