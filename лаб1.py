print(s, type(s))
print(b, type(b))
print(l, type(l))
print(t, type(t))
print(d, type(d))
print(st, type(st))
print(n, type(n))

# Всі оператори
x, y = 10, 3

# Арифметика
print(x + y, x - y, x * y, x / y, x // y, x % y, x ** y)

# Порівняння
print(x > y, x < y, x >= y, x <= y, x == y)

